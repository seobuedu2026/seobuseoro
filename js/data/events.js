const CUSTOM_EVENTS_KEY = "seobu_custom_events";

// 현재 활성화된 모든 행사 목록 반환
export function getEvents() {
  const custom = localStorage.getItem(CUSTOM_EVENTS_KEY);
  if (custom) {
    try {
      const parsed = JSON.parse(custom);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    } catch (e) {
      console.error("Failed to parse custom events", e);
    }
  }
  return DEFAULT_EVENTS_DATA;
}

// 이벤트 목록 저장
export function saveEvents(eventsList) {
  localStorage.setItem(CUSTOM_EVENTS_KEY, JSON.stringify(eventsList));
  window.dispatchEvent(new CustomEvent("events-updated", { detail: { events: eventsList } }));
}

// 기본 데이터로 초기화
export function resetEventsToDefault() {
  localStorage.removeItem(CUSTOM_EVENTS_KEY);
  window.dispatchEvent(new CustomEvent("events-updated", { detail: { events: DEFAULT_EVENTS_DATA } }));
}

// ============================================================================
// 엑셀 행(Row) 데이터를 웹사이트 이벤트 객체로 자동 변환하는 정밀 파서
// ============================================================================
export function parseExcelRowToEvent(row, index) {
  // 열 필드명 유연성 확보 (키 이름이 '연수명', '연수 명', '행사명' 등 다양할 수 있음)
  const getField = (keys) => {
    for (const k of keys) {
      for (const rowKey in row) {
        if (rowKey.replace(/\s+/g, "").toLowerCase() === k.replace(/\s+/g, "").toLowerCase()) {
          return String(row[rowKey] || "").trim();
        }
      }
    }
    return "";
  };

  const seq = getField(["연번", "no", "id", "순번"]) || String(index + 1);
  const manager = getField(["담당장학사", "담당자", "장학사", "manager"]);
  const rawTitle = getField(["연수명", "행사명", "프로그램명", "title"]);
  const rawDateTime = getField(["일시", "일자", "시간", "date", "datetime"]);
  const location = getField(["장소", "연수장소", "location"]);
  const target = getField(["대상", "연수대상", "참석대상", "target"]);
  const description = getField(["내용", "연수내용", "상세내용", "description"]);
  const applyMethod = getField(["신청방법", "신청", "비고", "apply"]);

  if (!rawTitle && !rawDateTime) return null;

  // 1. 연수명 및 서브타이틀 분리
  let title = rawTitle;
  let subtitle = "";

  // 괄호 추출 (예: (수다박스) 연구부장 협의회)
  if (title.startsWith("(") && title.includes(")")) {
    const endIdx = title.indexOf(")");
    const prefix = title.substring(1, endIdx);
    const rest = title.substring(endIdx + 1).trim();
    if (prefix.includes("수다박스") || prefix.includes("연수") || prefix.includes("특강")) {
      title = prefix;
      subtitle = rest;
    }
  } else if (title.includes("特강") || title.includes("특강")) {
    const parts = title.split("특강");
    if (parts.length > 1 && parts[1].trim()) {
      title = parts[0].trim() + " 특강";
      subtitle = parts[1].trim();
    }
  }

  // 2. 카테고리 자동 분류
  let category = "workshop";
  let categoryLabel = "연수·워크숍";
  let categoryClass = "cat-workshop";

  const fullText = (rawTitle + " " + subtitle + " " + description).toLowerCase();

  if (fullText.includes("수다박스") || fullText.includes("협의회") || fullText.includes("부장") || fullText.includes("학적")) {
    category = "sudabox";
    categoryLabel = "수다박스";
    categoryClass = "cat-sudabox";
  } else if (fullText.includes("특강") || fullText.includes("작가") || fullText.includes("교수") || fullText.includes("학부모 특강")) {
    category = "lecture";
    categoryLabel = "특강";
    categoryClass = "cat-lecture";
  } else if (fullText.includes("멘토링") || fullText.includes("저경력") || fullText.includes("신규교감")) {
    category = "mentoring";
    categoryLabel = "멘토링";
    categoryClass = "cat-mentoring";
  } else if (fullText.includes("교육콘서트") || fullText.includes("수업나눔") || fullText.includes("수업사례")) {
    category = "sharing";
    categoryLabel = "수업나눔 교육콘서트";
    categoryClass = "cat-sharing";
  } else if (fullText.includes("성과보고회") || fullText.includes("성과공유") || fullText.includes("한마당") || fullText.includes("결과보고")) {
    category = "festival";
    categoryLabel = "성과공유·보고·한마당";
    categoryClass = "cat-festival";
  }

  // 3. 일시(날짜 및 시간) 정밀 파싱
  // 지원 패턴: '9. 9.(수) 15:00~16:30', '2026. 10. 6.(화) 15:00~17:00', '9월 18일(금) 15:00' 등
  let year = 2026;
  let month = 9;
  let day = 1;
  let time = "15:00 ~ 17:00";

  // 연도 추출
  const yearMatch = rawDateTime.match(/(\d{4})\s*[년\.]/);
  if (yearMatch) {
    year = parseInt(yearMatch[1], 10);
  }

  // 월 추출 (예: '9.', '9월', '10.')
  const monthMatch = rawDateTime.match(/(\d{1,2})\s*[월\.]/);
  if (monthMatch) {
    month = parseInt(monthMatch[1], 10);
  }

  // 일 추출 (예: '9. 9.' 또는 '10. 6.' 또는 '18일')
  const dayMatch = rawDateTime.match(/[월\.]\s*(\d{1,2})\s*[일\.\(]/);
  if (dayMatch) {
    day = parseInt(dayMatch[1], 10);
  } else {
    // 12/2 형태 처리
    const slashMatch = rawDateTime.match(/12\/(\d{1,2})/);
    if (slashMatch) {
      day = `12/${slashMatch[1]}`;
    }
  }

  // 시간 추출 (예: 15:00~16:30, 09:00~17:00 등)
  const timeMatch = rawDateTime.match(/(\d{1,2}:\d{2})\s*[~-]\s*(\d{1,2}:\d{2})/);
  if (timeMatch) {
    time = `${timeMatch[1]} ~ ${timeMatch[2]}`;
  }

  const dateStr = typeof day === "number" 
    ? `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`
    : `${year}-12-02`;

  return {
    id: `excel-ev-${Date.now()}-${seq}`,
    month,
    year,
    day,
    dateStr,
    title,
    subtitle,
    category,
    categoryLabel,
    categoryClass,
    time,
    location: location || "추후 안내",
    target: target || "관내 교원",
    instructor: manager ? `${manager} (서부교육지원청)` : "초등교육지원과 장학진",
    manager,
    description: description || "상세 일정은 공문을 통해 확인하시기 바랍니다.",
    applyMethod: applyMethod || "온라인 링크",
    applyUrl: applyMethod.includes("링크") || applyMethod.includes("유레카") ? "https://senedu.kr" : ""
  };
}
